window.pickPersona = function (mood, rnd) {
  // mood: 'random' | 'nice' | 'mean'
  const w = PERSONAS.map((p) => mood === 'nice' ? Math.max(0.15, 1 + p.tone * 0.9) : mood === 'mean' ? Math.max(0.15, 1 - p.tone * 0.9) : 1);
  let t = rnd() * w.reduce((a, b) => a + b, 0);
  for (let i = 0; i < PERSONAS.length; i++) { t -= w[i]; if (t <= 0) return PERSONAS[i]; }
  return PERSONAS[PERSONAS.length - 1];
};

